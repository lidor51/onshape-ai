import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { loadLocalFixture, sha256 } from './generate.mjs';
import { finalRepairSource } from './final-repair.mjs';

const { task } = await loadLocalFixture();

test('final source fits 6000 characters and exports one empty-precondition geometry feature', () => {
  for (const phase of ['baseline', 'revision']) {
    const source = finalRepairSource(task, phase);
    assert.ok(source.length <= 6000, `${phase}: ${source.length}`);
    assert.ok(source.split('\n').every(line => line.length < 1200));
    assert.equal([...source.matchAll(/export /g)].length, 1);
    assert.match(source, /export const officialIntakeFinal = defineFeature/);
    assert.match(source, /precondition\{\}/);
    assert.match(source, /^FeatureScript 3070;/);
    assert.match(source, /version:"3070.0"/);
    assert.doesNotMatch(source, /officialIntakeExpected|officialIntakeAssert|packed|typeof|assertionsPassed|\[true,false\]/);
    for (const symbol of ['fCuboid', 'fCylinder', 'opBoolean', 'SUBTRACTION', 'EXCLUDE_FROM_BOM',
      'evBox3d', 'evVolume', 'evSurfaceDefinition', 'GeometryType.CYLINDER', 'coordSystem.zAxis',
      'OIM1|', 'emit("BEGIN"', 'emit("END"', 'emit("P|"', 'emit("C|"']) {
      assert.ok(source.includes(symbol), symbol);
    }
    for (const role of task.requiredParts) assert.ok(source.includes(`"${role}"`), role);
  }
});

test('revision differs only in numeric default fields; create and test use the same export', () => {
  const baseline = finalRepairSource(task);
  const revision = finalRepairSource(task, 'revision');
  assert.equal(baseline.replace('"innerWidth":340,"rollerGap":100', '"innerWidth":360,"rollerGap":95'), revision);
  assert.ok(baseline.replace(/\s/g, '').endsWith('},{"innerWidth":340,"rollerGap":100,"plateThickness":6.35});'),
    'Explicit numeric default map closes the feature');
  assert.throws(() => finalRepairSource(task, 'other'), /Invalid phase/);
});

function unknownIdentifiers(source) {
  const text = source.replace(/"(?:\\.|[^"\\])*"/g, '""');
  const declared = new Set([
    ...[...text.matchAll(/\b(?:function|const|var)\s+([A-Za-z_]\w*)/g)].map(match => match[1]),
    ...[...text.matchAll(/\b([A-Za-z_]\w*)\s+is\s+/g)].map(match => match[1]),
  ]);
  const known = new Set(('FeatureScript import path version function is const var for in if annotation export precondition true ' +
    'Context Id Vector vector number array string map fCuboid fCylinder millimeter setProperty qCreatedBy EntityType PropertyType ' +
    'size append opBoolean qUnion BooleanOperationType println qBodyType BodyType evBox3d evVolume evaluateQuery ' +
    'qGeometry qOwnedByBody GeometryType evSurfaceDefinition defineFeature').split(' '));
  return [...new Set([...text.matchAll(/\b[A-Za-z_]\w*/g)].filter(match =>
    text[match.index - 1] !== '.' && !declared.has(match[0]) && !known.has(match[0])).map(match => match[0]))];
}

test('lexical smoke check finds no unknown bare identifiers; it is not an Onshape compiler', () => {
  const source = finalRepairSource(task);
  assert.deepEqual(unknownIdentifiers(source), []);
  assert.deepEqual(unknownIdentifiers(source.replace('evVolume(context', 'missingEvaluator(context')), ['missingEvaluator']);
});

test('saved test/create payloads use exact final source bytes and honest manifest hashes', () => {
  const read = name => readFileSync(new URL(`./artifacts/${name}`, import.meta.url), 'utf8');
  const manifest = JSON.parse(read('final-repair-manifest.json'));
  assert.equal(manifest.status, 'FINAL_REPAIR_2_OF_2_READY_NOT_EXECUTED');
  assert.equal(manifest.officialCalls, 0);
  assert.equal(manifest.onshapeCompilation, 'UNVERIFIED');
  for (const phase of ['baseline', 'revision']) {
    const name = `final-repair-${phase}`;
    const source = read(`${name}.fs`);
    assert.ok(source === finalRepairSource(task, phase), `${phase} generated byte identity`);
    assert.deepEqual(JSON.parse(read(`${name}.test.payload.json`)), { code: source });
    assert.deepEqual(JSON.parse(read(`${name}.create.payload.json`)), {
      feature_name: 'OfficialIntakeFinal', feature_code: source, clean: false,
    });
    const entry = manifest.files.find(file => file.phase === phase);
    assert.equal(entry.sourceSha256, sha256(source));
    assert.equal(entry.sourceCharacters, source.length);
  }
});